# ── Public entry point ────────────────────────────────────────────

def discover_leads(
    candidate_id: str,
    search_queries: dict,
    candidate_model=None,   # CandidateModel — used for pre-scoring before the cap
) -> tuple[list[RawLead], list[RawLead]]:
    """
    Discover raw job leads for a candidate.

    Supabase-level dedup guard: checks pipeline_status in the DB before
    launching actors. If status is already 'discovering', returns immediately.
    This works across multiple Streamlit processes (unlike threading.Lock).

    ALL channels run FULLY IN PARALLEL via ThreadPoolExecutor:
      - LinkedIn Direct: one actor call per role group (primary title + aliases)
      - LinkedIn Indirect: one actor call for all hidden_signals combined
      - Wellfound: ONE actor call total (all URLs redirect to /location/india)
      - YC Jobs: concurrent HTTP scrape (no API key needed)
    """
    from db.queries import update_candidate_status, get_candidate

    # ── Supabase-level dedup guard ────────────────────────────────────────────
    # Prevents duplicate pipeline runs across Streamlit Cloud workers.
    # Covers ALL in-progress statuses so the gap between 'discovering' → 
    # 'discovered' → 'ranking' cannot be exploited by a rerender.
    existing = get_candidate(candidate_id)
    current_status = existing.get("pipeline_status") if existing else None
    if current_status in ("discovering", "discovered", "ranking", "ranked"):
        log.warning(
            "S3: BLOCKED — candidate %s already has status '%s'. Skipping duplicate run.",
            candidate_id, current_status,
        )
        return [], []

    update_candidate_status(candidate_id, "discovering")
    log.info("S3: Starting lead discovery for candidate %s", candidate_id)

    # Parse role_groups (new format) or fall back to formal_platforms (legacy)
    role_groups_raw = search_queries.get("role_groups", [])
    hidden_queries  = search_queries.get("hidden_signals", [])

    if role_groups_raw:
        groups = role_groups_raw
    else:
        # Legacy: wrap each primary title as a single-title group
        groups = [
            {"role_title": q, "search_titles": [q], "hidden_signals": []}
            for q in search_queries.get("formal_platforms", [])
        ]

    log.info("S3: %d role groups: %s",
             len(groups), [g.get("role_title") for g in groups])

    if not APIFY_API_KEY:
        log.warning("S3: APIFY_API_KEY not set — skipping all Apify channels")
        return [], []

    # Assemble parallel task list: (label, fn, args)
    tasks: list[tuple[str, object, tuple]] = []

    # LinkedIn Direct — one actor call per role group
    for g in groups:
        title         = g.get("role_title", "unknown")
        search_titles = g.get("search_titles") or [title]
        tasks.append((
            f"LinkedIn Direct [{title}]",
            _run_linkedin_jobs_group,
            (search_titles, title),
        ))

    # Wellfound — ONE actor call PER role_title (exact title, not aliases)
    # Each role title gets its own Wellfound search URL so we cover all job types.
    for g in groups:
        title = g.get("role_title", "")
        if title:
            tasks.append((
                f"Wellfound [{title}]",
                _run_wellfound_channel,
                ([title],),   # one URL built from the exact role_title
            ))

    # LinkedIn Indirect — all hidden_signals in one call
    all_hidden = list(hidden_queries)
    for g in groups:
        all_hidden.extend(g.get("hidden_signals") or [])
    all_hidden = list(dict.fromkeys(all_hidden))
    if all_hidden:
        tasks.append(("LinkedIn Indirect", _run_apify_post_scraper_channel, (all_hidden,)))

    # YC Jobs (Cutshort removed — Tavily is permanently dead, 432 errors)
    if all_primary:
        tasks.append(("YC Jobs", _run_yc_jobs_channel, (all_primary,)))

    # Execute all tasks in parallel
    direct_leads:   list[RawLead] = []
    indirect_leads: list[RawLead] = []
    failed_channels: list[str]    = []

    global discovery_partial
    discovery_partial = False

    log.info("S3: Launching %d parallel scrape tasks simultaneously", len(tasks))
    with ThreadPoolExecutor(max_workers=max(len(tasks), 1)) as executor:
        future_map = {
            executor.submit(fn, *args): label
            for label, fn, args in tasks
        }
        for future in as_completed(future_map):
            label = future_map[future]
            try:
                results: list[RawLead] = future.result()
                if "Indirect" in label:
                    indirect_leads.extend(results)
                else:
                    direct_leads.extend(results)
                total_so_far = len(direct_leads) + len(indirect_leads)
                log.info("S3: ✅ %-45s → %d leads  (running total: %d)",
                         label, len(results), total_so_far)
            except Exception as exc:
                total_so_far = len(direct_leads) + len(indirect_leads)
                failed_channels.append(label)
                if total_so_far >= PARTIAL_RESULT_THRESHOLD:
                    # We already have enough — demote failure to a warning
                    log.warning(
                        "S3: ⚠ %-45s → FAILED (ignored — %d leads already collected): %s",
                        label, total_so_far, exc,
                    )
                else:
                    log.error("S3: ❌ %-45s → FAILED: %s", label, exc)

    total_raw = len(direct_leads) + len(indirect_leads)

    if failed_channels and total_raw >= PARTIAL_RESULT_THRESHOLD:
        discovery_partial = True
        log.warning(
            "S3: Partial result mode — %d leads collected, %d channel(s) failed: %s",
            total_raw, len(failed_channels), failed_channels,
        )
    elif failed_channels:
        log.warning(
            "S3: %d channel(s) failed and only %d leads collected (below threshold %d). "
            "Proceeding anyway.",
            len(failed_channels), total_raw, PARTIAL_RESULT_THRESHOLD,
        )

    # Enrich + dedup
    if direct_leads:
        direct_leads = _enrich_company_stages(direct_leads)
        direct_leads = _enrich_hiring_managers(direct_leads)

    direct_leads   = _dedup_within(direct_leads)
    indirect_leads = _dedup_within(indirect_leads)
    direct_leads, indirect_leads = _dedup_cross_channel(direct_leads, indirect_leads)


    # ── Pre-score and sort direct leads (best-first ordering) ────────────────
    # No hard cap — ALL scraped leads go to the DB.
    # Pre-scoring keeps the highest-quality leads ordered first so Stage 4
    # sees the best candidates when it fetches from the matches table.
    if direct_leads and candidate_model is not None:
        try:
            from pipeline.s4_rank import _score_direct_initial
            scored_pairs = []
            for lead in direct_leads:
                match_dict = {
                    "role_title":            lead.role_title,
                    "company_name":          lead.company_name,
                    "company_stage_label":   lead.company_stage_label,
                    "description":           lead.description,
                    "compensation_estimate": lead.compensation_estimate,
                    "posted_at":             lead.posted_at,
                }
                prescore, _ = _score_direct_initial(match_dict, candidate_model)
                scored_pairs.append((prescore, lead))
            scored_pairs.sort(key=lambda x: x[0], reverse=True)
            direct_leads = [lead for _, lead in scored_pairs]
            log.info(
                "S3: Pre-scored %d direct leads — top: %.2f | bottom: %.2f — ALL going to DB",
                len(direct_leads),
                scored_pairs[0][0] if scored_pairs else 0,
                scored_pairs[-1][0] if scored_pairs else 0,
            )
        except Exception as e:
            log.warning("S3: Pre-scoring failed (%s) — leads kept in scrape order", e)

    log.info("S3: Final — %d direct + %d indirect leads — ALL being persisted to DB",
             len(direct_leads), len(indirect_leads))

    _persist_leads(candidate_id, direct_leads, indirect_leads)
    update_candidate_status(candidate_id, "discovered")

    return direct_leads, indirect_leads




# ── URL builders ──────────────────────────────────────────────────────────────

def _build_linkedin_jobs_url(role_title: str, location: str = "India") -> str:
    """Build a LinkedIn Jobs search URL for a given role title."""
    params = {"keywords": role_title, "location": location, "position": 1, "pageNum": 0}
    return "https://www.linkedin.com/jobs/search/?" + urlencode(params)


