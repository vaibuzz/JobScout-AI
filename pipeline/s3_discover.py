def _build_wellfound_url(role_title: str, country: str = "india") -> str:
    """Build a Wellfound role+location URL. Maps niche titles to valid category slugs."""
    key  = role_title.lower().strip()
    slug = _WELLFOUND_SLUG_MAP.get(key) or re.sub(r"[^a-z0-9]+", "-", key).strip("-")
    return f"https://wellfound.com/role/l/{slug}/{country}"




# ── Channel A1b: LinkedIn Jobs — Role-Group Aware (─────────────────────

def _run_linkedin_jobs_group(search_titles: list[str], role_label: str) -> list[RawLead]:
    """
    Run Apify LinkedIn Jobs Scraper for ONE role group.
    Sends all titles (primary + aliases) as separate URLs in a SINGLE actor call.
    Returns up to 100 leads (reduced from 200 since aliases improve precision).

    Logs include the role_label so every actor run is traceable:
      [LinkedIn Direct [Chief of Staff]] runId:abc RUNNING
      [LinkedIn Direct [Chief of Staff]] runId:abc COMPLETE → 73 leads
    """
    try:
        from apify_client import ApifyClient
        client = ApifyClient(APIFY_API_KEY)
    except ImportError:
        log.error("S3[A1][%s]: apify-client not installed", role_label)
        return []

    unique_titles = list(dict.fromkeys(search_titles))
    urls = [_build_linkedin_jobs_url(t) for t in unique_titles]
    seen_job_ids: set[str] = set()
    leads: list[RawLead] = []

    log.info("S3[A1][%s]: Sending %d URLs to LinkedIn Jobs actor: %s",
             role_label, len(urls), unique_titles)
    try:
        run = client.actor(_ACTOR_LINKEDIN_JOBS).call(
            run_input={
                "urls":          urls,
                "count":         100,   # 100 per group (3 groups = 300 total max)
                "scrapeCompany": True,
            }
        )
        run_id = (run or {}).get("id", "?")
        items  = list(client.dataset(run["defaultDatasetId"]).iterate_items())
        log.info("S3[A1][%s]: runId:%s returned %d raw items",
                 role_label, run_id, len(items))

        for item in items:
            job_id = str(item.get("id", ""))
            if job_id and job_id in seen_job_ids:
                continue
            if job_id:
                seen_job_ids.add(job_id)
            lead = _parse_apify_linkedin_job(item)
            if lead:
                leads.append(lead)

    except Exception as e:
        log.error("S3[A1][%s]: Actor FAILED: %s", role_label, e)

    return leads

