"""
Stage 3: Lead Discovery

Two channels run in parallel:

  Channel A — Formal Platforms (direct_leads table)
    A1: Apify LinkedIn Jobs Scraper  (actor: hKByXkMQaC5Qt9UMN)
        Input: generated LinkedIn search URLs — one per role title.
        Returns job poster name + LinkedIn URL (hiring manager).

    A2: Apify Wellfound Scraper      (actor: sqkHGNG0toRTR3ORV / clearpath/wellfound-api-ppe)
        Input: generated Wellfound role URLs — one per role title.
        Returns full job description + salary + company profile.

    Both channels pass ALL URLs in ONE actor call each.
    Company stage enrichment (Tavily) runs on ALL direct leads after scraping
    since neither actor returns a reliable stage label.

  Channel B — Hidden Signals (indirect_leads table)
    B1: Apify LinkedIn Post Search Scraper  (actor: buIWk2uOUzTmcLsuB)
        Input: "#Hiring {role}" search phrases generated by Stage 2.
        Gemini extracts company + role from each post in batches of 8.
        hiring_manager data comes from post author — reliable, not inferred.

Three-layer deduplication:
    Layer 1: job ID / signal_url dedup within each channel
    Layer 2: rapidfuzz cross-channel dedup (85% company + 80% role title)
    Layer 3: Supabase upsert on_conflict when persisting

Output: direct leads written to direct_leads table, indirect to indirect_leads table.
        Match placeholder records created in matches table for Stage 4 to score.
"""
